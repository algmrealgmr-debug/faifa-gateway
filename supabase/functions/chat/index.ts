const normalizeMessages = (body: unknown): Array<{ role: "user" | "assistant"; content: string }> => {
  if (!body || typeof body !== "object") return [];

  const payload = body as {
    prompt?: unknown;
    message?: unknown;
    messages?: Array<{ role?: string; content?: unknown }>;
  };

  const MAX_MSG_LEN = 2000;
  const MAX_MESSAGES = 20;
  const clamp = (s: string) => s.trim().slice(0, MAX_MSG_LEN);

  if (typeof payload.prompt === "string") {
    return [{ role: "user", content: clamp(payload.prompt) }];
  }
  if (typeof payload.message === "string") {
    return [{ role: "user", content: clamp(payload.message) }];
  }
  if (Array.isArray(payload.messages)) {
    return payload.messages
      .slice(-MAX_MESSAGES)
      .filter((m) => typeof m?.content === "string" && (m.role === "user" || m.role === "assistant"))
      .map((m) => ({
        role: m.role === "assistant" ? "assistant" as const : "user" as const,
        content: clamp(String(m.content)),
      }));
  }
  return [];
};

const toGeminiContents = (msgs: Array<{ role: "user" | "assistant"; content: string }>) => {
  const out: Array<{ role: "user" | "model"; parts: Array<{ text: string }> }> = [];
  for (const m of msgs) {
    const role = m.role === "assistant" ? "model" : "user";
    if (out.length > 0 && out[out.length - 1].role === role) {
      out[out.length - 1].parts[0].text += "\n" + m.content;
    } else {
      out.push({ role, parts: [{ text: m.content }] });
    }
  }
  return out;
};

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response("ok", { status: 200, headers: corsHeaders });
  }

  if (req.method !== "POST") {
    return jsonResponse({ error: "METHOD_NOT_ALLOWED", message: "Only POST requests are allowed." }, 405);
  }

  try {
    const apiKey = Deno.env.get("GEMINI_API_KEY")?.trim();
    if (!apiKey) {
      return jsonResponse(
        { error: "MISSING_GEMINI_API_KEY", message: "GEMINI_API_KEY is not configured." },
        400,
      );
    }

    let requestBody: unknown;
    try {
      requestBody = await req.json();
    } catch (_parseError) {
      return jsonResponse({ error: "INVALID_JSON", message: "Request body must be valid JSON." }, 400);
    }

    const conversation = normalizeMessages(requestBody);
    if (!conversation.length) {
      return jsonResponse(
        { error: "MISSING_PROMPT", message: "Request body must include a prompt or messages." },
        400,
      );
    }

    const totalLen = conversation.reduce((n, m) => n + m.content.length, 0);
    if (totalLen > 30000) {
      return jsonResponse(
        { error: "PROMPT_TOO_LARGE", message: "Conversation payload is too large." },
        413,
      );
    }

    const modelName = "gemini-1.5-flash";
    const genAI = new GoogleGenerativeAI(apiKey);
    const model = genAI.getGenerativeModel({
      model: modelName,
      systemInstruction: FAIFA_KNOWLEDGE,
    });

    const contents = toGeminiContents(conversation);
    const result = await model.generateContent({ contents });
    const response = await result.response;
    const generatedText = response.text().trim() || "عذراً، لم أتمكن من معالجة طلبك.";

    return jsonResponse({ message: generatedText, response: generatedText, model: modelName }, 200);
  } catch (error) {
    const errMsg = error instanceof Error ? error.message : String(error);
    console.error("Gemini chat function error:", error);

    if (errMsg.includes("429") || errMsg.includes("ResourceExhausted") || errMsg.includes("quota")) {
      return jsonResponse(
        { error: "RATE_LIMIT", message: "فيفاوي مشغول قليلاً الآن، فضلاً انتظر دقيقة وأعد السؤال.", status: 429 },
        200,
      );
    }

    if (errMsg.includes("API key not valid") || errMsg.includes("403")) {
      return jsonResponse(
        { error: "AUTH_ERROR", message: "خطأ في مفتاح Gemini API. تحقق من إعدادات المشروع.", status: 403 },
        200,
      );
    }

    return jsonResponse(
      {
        error: "GEMINI_API_ERROR",
        message: errMsg || "AI request failed.",
      },
      500,
    );
  }
});
